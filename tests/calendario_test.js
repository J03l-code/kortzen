const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const contexto = vm.createContext({document: {addEventListener() {}}});
vm.runInContext(fs.readFileSync('js/calendario-citas.js','utf8'),contexto);
const evento = (id,hora,duracion) => ({id,fecha_hora:'2026-11-19 '+hora+':00',duracion});
const distribuir = contexto.distribuirCitasCalendario;
let r = distribuir([evento(1,'10:00',60),evento(2,'10:30',60),evento(3,'11:00',60)]);
assert.equal(r.get(1).columnas,2);
assert.notEqual(r.get(1).carril,r.get(2).carril);
assert.notEqual(r.get(2).carril,r.get(3).carril);
r = distribuir([evento(1,'10:00',60),evento(2,'10:00',60),evento(3,'10:00',60)]);
assert.equal(new Set([...r.values()].map(e=>e.carril)).size,3);
r = distribuir([evento(1,'10:00',30),evento(2,'10:30',30),evento(3,'12:00',30)]);
assert.ok([...r.values()].every(e=>e.columnas===1 && e.carril===0));
const desordenados=[evento(2,'11:00',30),evento(1,'10:00',90)];
r=distribuir(desordenados);
assert.equal(desordenados[0].id,2);
assert.equal(r.get(1).columnas,2);
assert.equal(distribuir([]).size,0);
const jsSrc = fs.readFileSync('js/calendario-citas.js','utf8');
assert.ok(jsSrc.includes("vistaActual === 'lista'"), 'moverDia y change deben recargar la vista lista');
assert.ok(jsSrc.includes('irAListaFecha'), 'Debe existir navegacion sincronizada para vista lista');
const incSrc = fs.readFileSync('includes/calendario_citas.php','utf8');
assert.ok(incSrc.includes('data-fecha-lista'), 'Debe exponer data-fecha-lista para sincronizar filtros');
console.log('11 comprobaciones del calendario: correctas.');
